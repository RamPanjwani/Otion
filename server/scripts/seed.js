const purgeDemoData = async (emails) => {
  const users = await User.find({ email: { $in: emails } }).select('_id').lean();
  const userIds = users.map((user) => user._id);
  if (!userIds.length) return { users: 0, notes: 0 };

  const noteIds = await Note.find({ user: { $in: userIds } }).distinct('_id');
  const workspaceIds = await Workspace.find({ owner: { $in: userIds } }).distinct('_id');
  const noteScope = { $in: noteIds };
  const userScope = { $in: userIds };

  await Promise.all([
    SharePermission.deleteMany({ $or: [{ noteId: noteScope }, { userId: userScope }] }),
    UserNotePreference.deleteMany({ $or: [{ note: noteScope }, { user: userScope }] }),
    CollaborationState.deleteMany({ note: noteScope }),
    CollaborationUpdate.deleteMany({ note: noteScope }),
    NoteRevision.deleteMany({ $or: [{ note: noteScope }, { author: userScope }] }),
    PublicShare.deleteMany({ note: noteScope }),
    Comment.deleteMany({ $or: [{ note: noteScope }, { author: userScope }] }),
    Notification.deleteMany({ $or: [{ note: noteScope }, { actor: userScope }, { recipient: userScope }] }),
    Invitation.deleteMany({ $or: [{ note: noteScope }, { inviter: userScope }, { email: { $in: emails } }] }),
    WorkspaceMembership.deleteMany({ $or: [{ workspace: { $in: workspaceIds } }, { user: userScope }] }),
    Workspace.deleteMany({ _id: { $in: workspaceIds } }),
    Note.deleteMany({ _id: noteScope }),
  ]);
  await User.deleteMany({ _id: userScope });

  return { users: userIds.length, notes: noteIds.length };
};

const seed = async () => {
  if (!process.env.MONGO_URI) {
    throw new Error('MONGO_URI is not configured. Copy server/.env.example to server/.env and set MONGO_URI.');
  }

  await mongoose.connect(process.env.MONGO_URI);
  console.log(`Connected to database "${mongoose.connection.name}"`);

  const removed = await purgeDemoData(ACCOUNTS.map((account) => account.email));
  if (removed.users) console.log(`Removed previous demo data: ${removed.users} account(s), ${removed.notes} note(s)`);

  const users = {};
  for (const account of ACCOUNTS) {
    users[account.key] = await User.create({
      name: account.name,
      email: account.email,
      password: PASSWORD,
    });
  }

  const workspace = await ensurePersonalWorkspace(users.owner);
  workspace.name = 'Otion Demo';
  workspace.icon = '◇';
  await workspace.save();

  await WorkspaceMembership.create([
    { workspace: workspace._id, user: users.editor._id, role: 'guest', status: 'active' },
    { workspace: workspace._id, user: users.viewer._id, role: 'guest', status: 'active' },
  ]);

  const notes = {};
  for (const spec of NOTE_SPECS) {
    const note = await Note.create({
      title: spec.title,
      icon: spec.icon,
      content: spec.content,
      contentSchemaVersion: 3,
      user: users.owner._id,
      workspace: workspace._id,
      isArchived: Boolean(spec.archived),
      isPublished: Boolean(spec.published),
    });
    await UserNotePreference.create({
      user: users.owner._id,
      note: note._id,
      favorite: Boolean(spec.favorite),
      sortOrder: spec.sortOrder,
      lastOpenedAt: spec.sortOrder < 2 ? new Date() : null,
    });
    await recordRevision(note, users.owner._id, 'initial');
    for (const share of spec.shares || []) {
      await SharePermission.create({ noteId: note._id, userId: users[share.account]._id, role: share.role });
    }
    notes[spec.key] = note;
  }

  await recordRevision(notes.welcome, users.owner._id, 'manual', 'Kickoff');

  const research = await Note.create({
    title: 'Maya research notes',
    icon: '🔎',
    content: RESEARCH_CONTENT,
    contentSchemaVersion: 3,
    user: users.editor._id,
    workspace: workspace._id,
  });
  await SharePermission.create({ noteId: research._id, userId: users.owner._id, role: 'editor' });
  await UserNotePreference.create({
    user: users.owner._id,
    note: research._id,
    favorite: false,
    sortOrder: NOTE_SPECS.length,
  });
  await recordRevision(research, users.editor._id, 'initial');

  const publicToken = randomBytes(32).toString('base64url');
  await PublicShare.create({
    note: notes.onboarding._id,
    tokenHash: createHash('sha256').update(publicToken).digest('hex'),
    enabled: true,
    expiresAt: null,
    createdBy: users.owner._id,
  });

  const comment = await Comment.create({
    note: notes.design._id,
    blockId: 'design-p1',
    author: users.editor._id,
    content: '@demo@otion.app the margin rail works well — can we keep the new callout surface?',
    mentions: [users.owner._id],
  });
  await Notification.create({
    recipient: users.owner._id,
    type: 'mention',
    actor: users.editor._id,
    note: notes.design._id,
    comment: comment._id,
  });
  await Notification.create({
    recipient: users.editor._id,
    type: 'share',
    actor: users.owner._id,
    note: notes.welcome._id,
  });

  console.log('\nSeed complete');
  console.log(`  Workspace: ${workspace.name} (${workspace._id})`);
  console.log(`  Notes: ${NOTE_SPECS.length} owned by demo + 1 shared by Maya (1 archived, 1 published)`);
  console.log('\n  Accounts (password for all: ' + PASSWORD + ')');
  ACCOUNTS.forEach((account) => console.log(`    ${account.email.padEnd(18)} ${account.name}`));
  console.log('\n  Roles');
  console.log('    demo@otion.app  owner of the workspace and every seeded note');
  console.log('    maya@otion.app  editor on three notes, author of one shared note');
  console.log('    sam@otion.app   viewer on Welcome, commenter on Design sync notes');
  console.log(`\n  Public link: ${CLIENT_URL}/public/${publicToken}`);
  console.log('\n  Next: start the API and client, then sign in as demo@otion.app.');
};

seed()
  .then(async () => {
    await mongoose.disconnect();
    process.exit(0);
  })
  .catch(async (error) => {
    console.error('Seed failed:', error.message);
    await mongoose.disconnect().catch(() => undefined);
    process.exit(1);
  });
